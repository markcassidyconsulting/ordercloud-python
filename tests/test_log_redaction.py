from ordercloud.resources.products import ProductsResource
from tools.codegen.naming import path_param_to_snake
from tools.codegen.sensitivity import (
    NOT_SENSITIVE_PATH_PARAMS,
    REDACTION_MARKER,
    SENSITIVE_PATH_PARAMS,
)

from .conftest import TEST_BASE_URL

RESOURCES_DIR = Path(__file__).resolve().parent.parent / "src" / "ordercloud" / "resources"
GENERATED_HEADER = "# GENERATED by tools/codegen"
HTTP_METHODS = {"get", "post", "put", "patch", "delete", "request"}

# Python names a generated path may interpolate into a logged form.  A name
# that is also the snake_case form of a sensitive spec name is not cleared.
CLEARED_NAMES = {path_param_to_snake(n) for n in NOT_SENSITIVE_PATH_PARAMS} - {
    path_param_to_snake(n) for n in SENSITIVE_PATH_PARAMS
}


# ---------------------------------------------------------------------------
# Generated-code scan
# ---------------------------------------------------------------------------


def _interpolated_names(node: ast.JoinedStr) -> list[str] | None:
    """Names interpolated by an f-string, or ``None`` if any part is not a bare name."""
    names = []
    for value in node.values:
        if isinstance(value, ast.FormattedValue):
            if (
                not isinstance(value.value, ast.Name)
                or value.conversion != -1
                or value.format_spec is not None
            ):
                return None
            names.append(value.value.id)
    return names


def _literal_text(node: ast.JoinedStr) -> str:
    return "".join(
        v.value for v in node.values if isinstance(v, ast.Constant) and isinstance(v.value, str)
    )


def _check_logged_string(node: ast.expr, what: str) -> str | None:
    """Return a problem description if ``node`` may log anything but cleared names."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return None
    if isinstance(node, ast.JoinedStr):
        names = _interpolated_names(node)
        if names is None:
            return f"{what} interpolates something other than a bare name"
        uncleared = sorted(set(names) - CLEARED_NAMES)
        if uncleared:
            return f"{what} interpolates uncleared names {uncleared}"
        return None
    return f"{what} is a {type(node).__name__}, not a string literal or f-string"


def _check_path_arg(node: ast.expr) -> tuple[str, str | None]:
    """Classify an HTTP call's path argument: ``(kind, problem or None)``."""
    if isinstance(node, ast.Call):
        if not (isinstance(node.func, ast.Name) and node.func.id == "SensitivePath"):
            return "call", "path is a call to something other than SensitivePath"
        kwargs = {k.arg: k.value for k in node.keywords}
        if node.args or set(kwargs) != {"wire", "log_form"}:
            return "sensitive", "SensitivePath must be built with wire= and log_form= only"
        wire, log_form = kwargs["wire"], kwargs["log_form"]
        if not isinstance(wire, (ast.JoinedStr, ast.Constant)):
            return "sensitive", "SensitivePath wire is not a string literal or f-string"
        problem = _check_logged_string(log_form, "SensitivePath log_form")
        if problem:
            return "sensitive", problem
        text = log_form.value if isinstance(log_form, ast.Constant) else _literal_text(log_form)
        if REDACTION_MARKER not in text:
            return "sensitive", "SensitivePath log_form does not contain the redaction marker"
        return "sensitive", None
    return "plain", _check_logged_string(node, "path")


def _is_http_call(node: ast.AST) -> bool:
    """Whether ``node`` is ``self._http.<method>(...)``."""
    return (
        isinstance(node, ast.Call)
        and isinstance(node.func, ast.Attribute)
        and node.func.attr in HTTP_METHODS
        and isinstance(node.func.value, ast.Attribute)
        and node.func.value.attr == "_http"
        and isinstance(node.func.value.value, ast.Name)
        and node.func.value.value.id == "self"
    )


class TestGeneratedResourceScan:
    def test_every_logged_path_is_redacted_or_cleared(self):
        problems: list[str] = []
        modules = 0
        methods = 0
        calls = 0
        sensitive_by_module: dict[str, int] = {}

        for path in sorted(RESOURCES_DIR.glob("*.py")):
            source = path.read_text(encoding="utf-8")
            if not source.startswith(GENERATED_HEADER):
                continue
            modules += 1
            tree = ast.parse(source)
            for cls in (n for n in tree.body if isinstance(n, ast.ClassDef)):
                methods += sum(isinstance(n, ast.AsyncFunctionDef) for n in cls.body)
            for node in ast.walk(tree):
                if not _is_http_call(node):
                    continue
                calls += 1
                where = f"{path.name}:{node.lineno}"
                if not node.args:
                    problems.append(f"{where}: HTTP call without a positional path")
                    continue
                kind, problem = _check_path_arg(node.args[0])
                if problem:
                    problems.append(f"{where}: {problem}")
                if kind == "sensitive":
                    sensitive_by_module[path.name] = sensitive_by_module.get(path.name, 0) + 1

        assert problems == []
        # Not vacuous: the scan saw the generated code, one HTTP call per method,
        # and the known credential-bearing routes in their redacted form.
        assert modules >= 60
        assert methods > 600
        assert calls == methods
        assert sensitive_by_module.get("forgotten_credentials.py", 0) >= 1
        assert sensitive_by_module.get("group_orders.py", 0) >= 1
        assert sensitive_by_module.get("me.py", 0) >= 8

    def test_scan_rejects_an_unredacted_credential_path(self):
        """The checker itself fails on the shape the redaction replaced."""
        call = ast.parse('self._http.put(f"/password/reset/{verification_code}")').body[0]
        assert isinstance(call, ast.Expr) and _is_http_call(call.value)
        _, problem = _check_path_arg(call.value.args[0])
        assert problem is not None and "verification_code" in problem

    def test_scan_rejects_a_sensitive_path_logging_the_secret(self):
        expr = ast.parse(
            'SensitivePath(wire=f"/grouporders/{invitation_id}/token", '
            'log_form=f"/grouporders/{invitation_id}/token")'
        ).body[0]
        assert isinstance(expr, ast.Expr)
        _, problem = _check_path_arg(expr.value)
        assert problem is not None and "invitation_id" in problem


