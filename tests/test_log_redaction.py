CODE = "vc-7Q2X9-reset"
INVITE = "inv-K81Z-group"
ANON = "anon-token-W3T5"


def _ordercloud_messages(caplog: pytest.LogCaptureFixture) -> list[str]:
    return [r.getMessage() for r in caplog.records if r.name.startswith("ordercloud")]


def _leaks(caplog: pytest.LogCaptureFixture, secret: str) -> list[str]:
    return [
        f"{r.getMessage()} {r.msg!r} {r.args!r}"
        for r in caplog.records
        if r.name.startswith("ordercloud") and secret in f"{r.getMessage()} {r.msg!r} {r.args!r}"
    ]


class TestEndToEndRedaction:
    @respx.mock
    async def test_password_reset_logs_marker_not_code(
        self, http_client: HttpClient, caplog: pytest.LogCaptureFixture
    ):
        route = respx.put(f"{TEST_BASE_URL}/password/reset/{CODE}").mock(return_value=Response(204))
        with caplog.at_level(logging.DEBUG, logger="ordercloud"):
            await ForgottenCredentialsResource(http_client).reset_password_by_verification_code(
                CODE, {"ClientID": "c", "Username": "u", "Password": "p"}
            )
        assert route.call_count == 1
        messages = _ordercloud_messages(caplog)
        assert "Request: PUT /password/reset/***" in messages
        assert "Response: PUT /password/reset/*** 204" in messages
        assert _leaks(caplog, CODE) == []

    @respx.mock
    async def test_group_order_token_logs_marker_not_invitation(
        self, http_client: HttpClient, caplog: pytest.LogCaptureFixture
    ):
        route = respx.post(f"{TEST_BASE_URL}/grouporders/{INVITE}/token").mock(
            return_value=Response(200, json={"access_token": "tok", "expires_in": 600})
        )
        with caplog.at_level(logging.DEBUG, logger="ordercloud"):
            token = await GroupOrdersResource(http_client).get_token(INVITE)
        assert route.call_count == 1
        assert token.access_token == "tok"
        assert "Request: POST /grouporders/***/token" in _ordercloud_messages(caplog)
        assert _leaks(caplog, INVITE) == []

    @respx.mock
    async def test_collection_invitation_keeps_collection_id_redacts_invitation(
        self, http_client: HttpClient, caplog: pytest.LogCaptureFixture
    ):
        route = respx.post(
            f"{TEST_BASE_URL}/me/productcollections/col-1/invitations/accept/{INVITE}"
        ).mock(return_value=Response(204))
        with caplog.at_level(logging.DEBUG, logger="ordercloud"):
            await MeResource(http_client).accept_product_collection_invitation("col-1", INVITE)
        assert route.call_count == 1
        assert (
            "Request: POST /me/productcollections/col-1/invitations/accept/***"
            in _ordercloud_messages(caplog)
        )
        assert _leaks(caplog, INVITE) == []

    @respx.mock
    async def test_ordinary_path_is_logged_unchanged(
        self, http_client: HttpClient, caplog: pytest.LogCaptureFixture
    ):
        respx.get(f"{TEST_BASE_URL}/products/p-123").mock(
            return_value=Response(200, json={"ID": "p-123"})
        )
        with caplog.at_level(logging.DEBUG, logger="ordercloud"):
            await ProductsResource(http_client).get("p-123")
        messages = _ordercloud_messages(caplog)
        assert "Request: GET /products/p-123" in messages
        assert "Response: GET /products/p-123 200" in messages

    @respx.mock
    async def test_query_parameter_token_is_not_logged(
        self, http_client: HttpClient, caplog: pytest.LogCaptureFixture
    ):
        route = respx.put(f"{TEST_BASE_URL}/me/orders").mock(return_value=Response(204))
        with caplog.at_level(logging.DEBUG, logger="ordercloud"):
            await MeResource(http_client).transfer_anon_user_order(anon_user_token=ANON)
        # The token really was sent, so the absence below is meaningful.
        assert route.calls[0].request.url.params["anonUserToken"] == ANON
        assert "Request: PUT /me/orders" in _ordercloud_messages(caplog)
        assert _leaks(caplog, ANON) == []

    @respx.mock
    async def test_error_on_reset_route_does_not_carry_code(
        self, http_client: HttpClient, caplog: pytest.LogCaptureFixture
    ):
        respx.put(f"{TEST_BASE_URL}/password/reset/{CODE}").mock(
            return_value=Response(
                400,
                json={
                    "Errors": [{"ErrorCode": "NotFound", "Message": "Invalid verification code"}]
                },
            )
        )
        with caplog.at_level(logging.DEBUG, logger="ordercloud"):
            with pytest.raises(OrderCloudError) as exc_info:
                await ForgottenCredentialsResource(http_client).reset_password_by_verification_code(
                    CODE, {"ClientID": "c", "Username": "u"}
                )
        assert exc_info.value.status_code == 400
        assert CODE not in str(exc_info.value)
        assert _leaks(caplog, CODE) == []
